pub struct BuiltinProfile {
    pub file_name: &'static str,
    pub bytes: Vec<u8>,
}

pub fn reference_profile(key: &str) -> Option<BuiltinProfile> {
    let spec = SPACES.iter().find(|space| space.key == key)?;
    Some(BuiltinProfile {
        file_name: spec.file_name,
        bytes: build_profile(spec),
    })
}

fn build_profile(spec: &SpaceSpec) -> Vec<u8> {
    let matrix = adapted_rgb_to_xyz(spec.primaries, spec.white, D50);
    let mut tags = vec![
        (sig(b"desc"), description_tag(spec.description)),
        (sig(b"cprt"), text_tag(b"Generated by Screenguard from published reference colorimetry; not a device calibration.")),
        (sig(b"wtpt"), xyz_tag(xy_to_xyz(D50.0, D50.1, 1.0))),
        (sig(b"rXYZ"), xyz_tag([matrix[0][0], matrix[1][0], matrix[2][0]])),
        (sig(b"gXYZ"), xyz_tag([matrix[0][1], matrix[1][1], matrix[2][1]])),
        (sig(b"bXYZ"), xyz_tag([matrix[0][2], matrix[1][2], matrix[2][2]])),
        (sig(b"rTRC"), curve_tag(spec.transfer)),
        (sig(b"gTRC"), curve_tag(spec.transfer)),
        (sig(b"bTRC"), curve_tag(spec.transfer)),
    ];
    tags.sort_by_key(|tag| tag.0);

    let table_size = 4 + tags.len() * 12;
    let mut offset = 128 + table_size;
    let mut table = Vec::with_capacity(table_size);
    let mut payload = Vec::new();
    push_u32(&mut table, tags.len() as u32);
    for (signature, data) in &tags {
        while offset % 4 != 0 {
            payload.push(0);
            offset += 1;
        }
        push_u32(&mut table, *signature);
        push_u32(&mut table, offset as u32);
        push_u32(&mut table, data.len() as u32);
        payload.extend_from_slice(data);
        offset += data.len();
    }

    let mut profile = vec![0u8; 128];
    profile[4..8].copy_from_slice(b"SGRD");
    profile[8..12].copy_from_slice(&0x0210_0000u32.to_be_bytes());
    profile[12..16].copy_from_slice(b"mntr");
    profile[16..20].copy_from_slice(b"RGB ");
    profile[20..24].copy_from_slice(b"XYZ ");
    // Deterministic profile creation timestamp.
    for (index, value) in [2026u16, 1, 1, 0, 0, 0].into_iter().enumerate() {
        profile[24 + index * 2..26 + index * 2].copy_from_slice(&value.to_be_bytes());
    }
    profile[36..40].copy_from_slice(b"acsp");
    profile[40..44].copy_from_slice(b"MSFT");
    profile[48..52].copy_from_slice(b"SGRD");
    profile[52..56].copy_from_slice(b"REF1");
    profile[64..68].copy_from_slice(&0u32.to_be_bytes()); // Perceptual rendering intent.
    profile[68..72].copy_from_slice(&fixed(0.9642).to_be_bytes());
    profile[72..76].copy_from_slice(&fixed(1.0).to_be_bytes());
    profile[76..80].copy_from_slice(&fixed(0.8249).to_be_bytes());
    profile[80..84].copy_from_slice(b"SGRD");
    profile.extend_from_slice(&table);
    profile.extend_from_slice(&payload);
    let length = profile.len() as u32;
    profile[0..4].copy_from_slice(&length.to_be_bytes());
    profile
}

fn description_tag(description: &str) -> Vec<u8> {
    let mut data = Vec::new();
    data.extend_from_slice(b"desc");
    push_u32(&mut data, 0);
    push_u32(&mut data, description.len() as u32 + 1);
    data.extend_from_slice(description.as_bytes());
    data.push(0);
    push_u32(&mut data, 0); // No Unicode localized string.
    push_u32(&mut data, 0);
    data.extend_from_slice(&0u16.to_be_bytes()); // ScriptCode code.
    data.push(0); // ScriptCode count.
    data.resize(data.len() + 67, 0);
    data
}

fn text_tag(text: &[u8]) -> Vec<u8> {
    let mut data = Vec::with_capacity(8 + text.len() + 1);
    data.extend_from_slice(b"text");
    push_u32(&mut data, 0);
    data.extend_from_slice(text);
    data.push(0);
    data
}

fn xyz_tag(xyz: [f64; 3]) -> Vec<u8> {
    let mut data = Vec::with_capacity(20);
    data.extend_from_slice(b"XYZ ");
    push_u32(&mut data, 0);
    for value in xyz {
        data.extend_from_slice(&fixed(value).to_be_bytes());
    }
    data
}

fn curve_tag(transfer: Transfer) -> Vec<u8> {
    const SAMPLES: usize = 4096;
    let mut data = Vec::with_capacity(12 + SAMPLES * 2);
    data.extend_from_slice(b"curv");
    push_u32(&mut data, 0);
    push_u32(&mut data, SAMPLES as u32);
    for index in 0..SAMPLES {
        let encoded = index as f64 / (SAMPLES - 1) as f64;
        let linear = match transfer {
            Transfer::Srgb => {
                if encoded <= 0.04045 {
                    encoded / 12.92
                } else {
                    ((encoded + 0.055) / 1.055).powf(2.4)
                }
            }
            Transfer::Gamma(gamma) => encoded.powf(gamma),
            Transfer::ProPhoto => {
                if encoded < 16.0 / 512.0 {
                    encoded / 16.0
                } else {
                    encoded.powf(1.8)
                }
            }
        };
        let sample = (linear.clamp(0.0, 1.0) * 65535.0).round() as u16;
        data.extend_from_slice(&sample.to_be_bytes());
    }
    data
}

fn xy_to_xyz(x: f64, y: f64, luminance: f64) -> [f64; 3] {
    [x * luminance / y, luminance, (1.0 - x - y) * luminance / y]
}

fn adapted_rgb_to_xyz(
    primaries: [(f64, f64); 3],
    source_white: (f64, f64),
    destination_white: (f64, f64),
) -> [[f64; 3]; 3] {
    let p = [
        xy_to_xyz(primaries[0].0, primaries[0].1, 1.0),
        xy_to_xyz(primaries[1].0, primaries[1].1, 1.0),
        xy_to_xyz(primaries[2].0, primaries[2].1, 1.0),
    ];
    let primary_matrix = [
        [p[0][0], p[1][0], p[2][0]],
        [p[0][1], p[1][1], p[2][1]],
        [p[0][2], p[1][2], p[2][2]],
    ];
    let source_xyz = xy_to_xyz(source_white.0, source_white.1, 1.0);
    let scale = multiply_vector(inverse(primary_matrix), source_xyz);
    let mut rgb_xyz = primary_matrix;
    for row in 0..3 {
        for column in 0..3 {
            rgb_xyz[row][column] *= scale[column];
        }
    }
    let bradford = [
        [0.8951, 0.2664, -0.1614],
        [-0.7502, 1.7135, 0.0367],
        [0.0389, -0.0685, 1.0296],
    ];
    let source_cone = multiply_vector(bradford, source_xyz);
    let destination_xyz = xy_to_xyz(destination_white.0, destination_white.1, 1.0);
    let destination_cone = multiply_vector(bradford, destination_xyz);
    let mut adaptation = bradford;
    for row in 0..3 {
        for column in 0..3 {
            adaptation[row][column] *= destination_cone[row] / source_cone[row];
        }
    }
    multiply(inverse(bradford), multiply(adaptation, rgb_xyz))
}

fn multiply(a: [[f64; 3]; 3], b: [[f64; 3]; 3]) -> [[f64; 3]; 3] {
    let mut result = [[0.0; 3]; 3];
    for row in 0..3 {
        for column in 0..3 {
            for k in 0..3 {
                result[row][column] += a[row][k] * b[k][column];
            }
        }
    }
    result
}

fn multiply_vector(a: [[f64; 3]; 3], b: [f64; 3]) -> [f64; 3] {
    let mut result = [0.0; 3];
    for row in 0..3 {
        for column in 0..3 {
            result[row] += a[row][column] * b[column];
        }
    }
    result
}

fn inverse(m: [[f64; 3]; 3]) -> [[f64; 3]; 3] {
    let det = m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1])
        - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
        + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]);
    let inv = [
        [
            m[1][1] * m[2][2] - m[1][2] * m[2][1],
            m[0][2] * m[2][1] - m[0][1] * m[2][2],
            m[0][1] * m[1][2] - m[0][2] * m[1][1],
        ],
        [
            m[1][2] * m[2][0] - m[1][0] * m[2][2],
            m[0][0] * m[2][2] - m[0][2] * m[2][0],
            m[0][2] * m[1][0] - m[0][0] * m[1][2],
        ],
        [
            m[1][0] * m[2][1] - m[1][1] * m[2][0],
            m[0][1] * m[2][0] - m[0][0] * m[2][1],
            m[0][0] * m[1][1] - m[0][1] * m[1][0],
        ],
    ];
    let mut result = inv;
    for row in &mut result {
        for value in row {
            *value /= det;
        }
    }
    result
}

fn fixed(value: f64) -> i32 {
    (value * 65536.0).round() as i32
}

fn sig(bytes: &[u8; 4]) -> u32 {
    u32::from_be_bytes(*bytes)
}

fn push_u32(out: &mut Vec<u8>, value: u32) {
    out.extend_from_slice(&value.to_be_bytes());
}

#[cfg(test)]
mod tests {
    use super::*;

    fn u32_at(data: &[u8], offset: usize) -> u32 {
        u32::from_be_bytes(data[offset..offset + 4].try_into().unwrap())
    }

    #[test]
    fn generated_profiles_have_valid_icc_v2_display_headers_and_tag_bounds() {
        for spec in SPACES {
            let profile = build_profile(spec);
            assert_eq!(u32_at(&profile, 0) as usize, profile.len(), "{}", spec.key);
            assert_eq!(&profile[8..12], &0x0210_0000u32.to_be_bytes());
            assert_eq!(&profile[12..16], b"mntr");
            assert_eq!(&profile[16..20], b"RGB ");
            assert_eq!(&profile[20..24], b"XYZ ");
            assert_eq!(&profile[36..40], b"acsp");
            let tag_count = u32_at(&profile, 128) as usize;
            assert_eq!(tag_count, 9);
            let table_end = 132 + tag_count * 12;
            let mut previous_signature = 0;
            for index in 0..tag_count {
                let item = 132 + index * 12;
                let signature = u32_at(&profile, item);
                let offset = u32_at(&profile, item + 4) as usize;
                let size = u32_at(&profile, item + 8) as usize;
                assert!(signature >= previous_signature);
                assert_eq!(offset % 4, 0);
                assert!(offset >= table_end);
                assert!(offset + size <= profile.len());
                previous_signature = signature;
            }
        }
    }

    #[test]
    fn adapted_colorants_sum_to_the_d50_profile_white() {
        for spec in SPACES {
            let matrix = adapted_rgb_to_xyz(spec.primaries, spec.white, D50);
            let sum = [
                matrix[0][0] + matrix[0][1] + matrix[0][2],
                matrix[1][0] + matrix[1][1] + matrix[1][2],
                matrix[2][0] + matrix[2][1] + matrix[2][2],
            ];
            let expected = xy_to_xyz(D50.0, D50.1, 1.0);
            for component in 0..3 {
                assert!(
                    (sum[component] - expected[component]).abs() < 0.0001,
                    "{} component {}: {} != {}",
                    spec.key,
                    component,
                    sum[component],
                    expected[component]
                );
            }
        }
    }

    #[test]
    fn standard_spaces_have_generated_profiles_but_gray_is_not_an_rgb_display_profile() {
        for key in [
            "srgb", "p3", "dcip3", "adobergb", "rec709", "rec2020", "prophoto",
        ] {
            let profile = reference_profile(key).expect(key);
            assert!(profile.file_name.ends_with(".icc"), "{}", key);
            assert_eq!(&profile.bytes[36..40], b"acsp", "{}", key);
        }
        assert!(reference_profile("gray").is_none());
        assert!(reference_profile("unknown").is_none());
    }
}
