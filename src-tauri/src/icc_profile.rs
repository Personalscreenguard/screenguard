//! Small, generated ICC v2 RGB display profiles for standard reference spaces.
//!
//! These profiles describe the reference color space only. They do not calibrate a
//! particular monitor; device calibration still requires a measured device profile.

#[derive(Clone, Copy)]
struct SpaceSpec {
    key: &'static str,
    file_name: &'static str,
    description: &'static str,
    primaries: [(f64, f64); 3],
    white: (f64, f64),
    transfer: Transfer,
}

#[derive(Clone, Copy)]
enum Transfer {
    Srgb,
    Gamma(f64),
    ProPhoto,
}

